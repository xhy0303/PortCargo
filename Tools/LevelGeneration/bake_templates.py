"""Bake screened campaign L51-L200 into deterministic, dependency-free mobile templates."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
levels = json.loads((root/'Assets/PortCargo/Data/Levels/catalog.json').read_text())['levels'][50:]
assert len(levels) == 150
rows=[]
for level in levels:
    stacks=level['stacks']
    witness=sorted(((int(box['id'].rsplit('B',1)[1]), s) for s,stack in enumerate(stacks) for box in stack['boxes']))
    assert [i for i,s in witness] == list(range(1,len(witness)+1))
    encoded='/'.join(''.join(b['type'] for b in stack['boxes']) for stack in stacks)
    encoded+='|'+ '/'.join(s['type']+str(s['capacity']) for s in level['ships'])
    encoded+='|'+''.join(str(s) for i,s in witness)
    rows.append('            "'+encoded+'", // '+level['id'])
factory=(Path(__file__).parent/'HardLevelTemplates.factory.txt').read_text()
source='''// Generated by Tools/LevelGeneration/bake_templates.py from screened L51-L200.
// Three tiers of 50 structures. Type/stack permutations preserve exact feasibility and difficulty.
namespace PortCargo.Core
{
    internal static class HardLevelTemplates
    {
        static readonly string[] Encoded = {
'''+ '\n'.join(rows)+'\n        };\n'+factory+'    }\n}\n'
(root/'Assets/PortCargo/Scripts/Core/HardLevelTemplates.cs').write_text(source)
print('Baked 150 verified structures, 3 difficulty tiers')
